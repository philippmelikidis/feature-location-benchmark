#!/usr/bin/env python3
"""
hierarchical_v16_retriever.py – LLM-gestützte Query-Expansion + Dense Stage 2.

Implements the asymmetric design from the FLBench report (Section 6):

Stage 1 (Coarse File Selection):
    - Pre-computed LLM expansions (code snippets, identifiers) are loaded
      from a JSON file generated by scripts/precompute_llm_expansions.py.
    - These terms + issue title are used as BM25 query against the coarse index.
    - This is a code-specific HyDE variant for BM25.

Stage 2 (Fine Chunk Ranking):
    - Dense retrieval (embedding-based) with Terms Filter on candidate files.
    - Full issue text (title + body) as query.

The LLM is NOT called at benchmark time — all expansions are pre-computed.
Run scripts/precompute_llm_expansions.py first!
"""

import json
from pathlib import Path
from typing import List, Tuple, Dict, Optional

from .base import BaseRetriever
from .es_retriever import ElasticsearchRetriever
from benchmark.chunking.base import BaseChunker, Chunk


# ─── Pre-computed Expansion Lookup ─────────────────────────────

class ExpansionLookup:
    """Loads pre-computed LLM expansions from JSON and provides lookup by query text."""

    def __init__(self, expansions_file: str):
        self.expansions_file = Path(expansions_file)
        self._by_sample_id: Dict[str, str] = {}
        self._by_title: Dict[str, str] = {}
        self._loaded = False

    def _load(self):
        if self._loaded:
            return

        if not self.expansions_file.exists():
            print(f"    [V16] WARNING: Expansions-Datei nicht gefunden: {self.expansions_file}")
            print(f"    [V16]   → Erst ausführen: python scripts/precompute_llm_expansions.py")
            self._loaded = True
            return

        with open(self.expansions_file, "r", encoding="utf-8") as f:
            data = json.load(f)

        expansions = data.get("expansions", {})
        for sid, entry in expansions.items():
            combined = entry.get("combined_query", "")
            if combined:
                self._by_sample_id[sid] = combined
                # Also index by title for fuzzy matching
                title = entry.get("title", "")
                if title:
                    self._by_title[title.strip().lower()] = combined

        print(f"    [V16] {len(self._by_sample_id)} pre-computed expansions geladen")
        self._loaded = True

    def lookup(self, query: str) -> Optional[str]:
        """Look up pre-computed expansion by matching the query title."""
        self._load()

        # Match by first line (title) of the query
        title = ""
        for line in query.split("\n"):
            line = line.strip()
            if line:
                title = line
                break

        title_key = title.strip().lower()
        if title_key in self._by_title:
            return self._by_title[title_key]

        return None

    def stats(self) -> Dict[str, int]:
        self._load()
        return {
            "total": len(self._by_sample_id),
            "by_title": len(self._by_title),
        }


# ─── Default expansions file path ─────────────────────────────

_DEFAULT_EXPANSIONS_FILE = str(
    Path(__file__).parent.parent / "data" / "llm_expansions_pandas.json"
)


def expansions_file_for_repo(repo_id: Optional[str]) -> str:
    """Return the pre-computed expansion file path for a given repo.

    Maps a repo id (e.g. "pandas", "pallets/flask") to
    data/llm_expansions_<short>.json so each repo loads its OWN expansions
    instead of always falling back to the pandas file. If repo_id is falsy,
    the pandas default is used (backward compatible).

    Prompt-Varianten: Ist die Env-Variable EXPANSION_VARIANT
    auf einen Nicht-Baseline-Wert gesetzt (z. B. "lean"), wird die
    Varianten-Datei llm_expansions_<repo>__<variante>.json geladen — so
    lassen sich alle llm_expanded-Conditions ohne neue Configs gegen eine
    Prompt-Variante fahren (Erzeugung:
    scripts/precompute_llm_expansions.py --prompt-variant <variante>).
    """
    import os
    variant = os.environ.get("EXPANSION_VARIANT", "").strip()
    suffix = f"__{variant}" if variant and variant != "baseline" else ""

    short = str(repo_id or "").split("/")[-1].strip().lower()
    if not short:
        if suffix:
            return _DEFAULT_EXPANSIONS_FILE.replace(".json", f"{suffix}.json")
        return _DEFAULT_EXPANSIONS_FILE
    return str(Path(__file__).parent.parent / "data"
               / f"llm_expansions_{short}{suffix}.json")


# ─── V16 Retriever ────────────────────────────────────────────

class HierarchicalV16Retriever(BaseRetriever):
    """
    Two-stage retriever with pre-computed LLM query expansion.

    Stage 1: Pre-computed LLM-expanded query (code terms) → BM25 on coarse index
    Stage 2: Full issue text → Dense/Hybrid retrieval with Terms Filter

    Args:
        expansions_file: Path to JSON with pre-computed LLM expansions
        stage1_query_mode: "llm_expanded" (default) or "title_only" (ablation)
        fine_retriever_type: "dense" (default, as per report) or "hybrid"
    """

    def __init__(
        self,
        es_url: str,
        index_prefix: str,
        condition_id: str,
        coarse_chunker: BaseChunker,
        fine_chunker: BaseChunker,
        coarse_retriever_type: str = "sparse",
        fine_retriever_type: str = "dense",
        embedding_model_name: Optional[str] = None,
        embedding_dims: int = 768,
        hybrid_alpha: float = 0.5,
        top_n_files: int = 20,
        coarse_score_aggregation: str = "max",
        # V16-specific
        expansions_file: Optional[str] = None,
        stage1_query_mode: str = "llm_expanded",
        stage2_query_mode: str = "full",
        # Kept for backward compat with config (ignored now)
        llm_api_url: str = "http://localhost:1234/v1",
        llm_model: Optional[str] = None,
        llm_temperature: float = 0.3,
        llm_timeout: float = 120.0,
        repo_name: str = "pandas",
    ):
        super().__init__(name=f"hier_v16_{condition_id}")
        self.es_url = es_url
        self.condition_id = condition_id
        self.coarse_chunker = coarse_chunker
        self.fine_chunker = fine_chunker
        self.top_n_files = top_n_files
        self.coarse_score_aggregation = coarse_score_aggregation
        self.stage1_query_mode = stage1_query_mode
        self.stage2_query_mode = stage2_query_mode

        # Pre-computed expansions lookup
        self._lookup = ExpansionLookup(expansions_file or _DEFAULT_EXPANSIONS_FILE)

        # Stats
        self._expansion_hits = 0
        self._expansion_misses = 0

        # Stage 1: BM25 coarse
        self._coarse = ElasticsearchRetriever(
            es_url=es_url,
            index_prefix=index_prefix,
            condition_id=f"{condition_id}_coarse",
            retriever_type=coarse_retriever_type,
            embedding_model_name=embedding_model_name if coarse_retriever_type != "sparse" else None,
            embedding_dims=embedding_dims,
            hybrid_alpha=hybrid_alpha,
        )

        # Stage 2: Dense/Hybrid fine retrieval
        self._fine = ElasticsearchRetriever(
            es_url=es_url,
            index_prefix=index_prefix,
            condition_id=f"{condition_id}_fine",
            retriever_type=fine_retriever_type,
            embedding_model_name=embedding_model_name,
            embedding_dims=embedding_dims,
            hybrid_alpha=hybrid_alpha,
        )

        self._fine_chunks: List[Chunk] = []
        self._fine_chunk_map: Dict[str, Chunk] = {}
        self._chunks_by_file: Dict[str, List[str]] = {}

        # Instrumentation
        self.last_coarse_files: List[str] = []
        self.last_coarse_hit_count: int = 0
        self.last_stage2_from_candidate_files: int = 0
        self.last_stage2_from_fallback: int = 0
        self.last_stage1_query: str = ""

    # ─── Indexing ──────────────────────────────────────────────────

    def index_repository(self, repo_path: Path, python_files: List[Path],
                         cache_context: Optional[dict] = None):
        """Build BOTH coarse and fine indices from the repo."""
        coarse_ctx = None
        fine_ctx = None
        if cache_context:
            coarse_ctx = {**cache_context, "chunker_strategy": self.coarse_chunker.name}
            fine_ctx = {**cache_context, "chunker_strategy": self.fine_chunker.name}

        print(f"  [HIER-V16] coarse chunking ({self.coarse_chunker.name})...")
        coarse_chunks = self.coarse_chunker.chunk_repository(repo_path, python_files)
        print(f"  [HIER-V16]   coarse_chunks={len(coarse_chunks)}")

        print(f"  [HIER-V16] coarse indexing (retriever={self._coarse.retriever_type})...")
        self._coarse.index(coarse_chunks, cache_context=coarse_ctx)

        print(f"  [HIER-V16] fine chunking ({self.fine_chunker.name})...")
        fine_chunks = self.fine_chunker.chunk_repository(repo_path, python_files)
        print(f"  [HIER-V16]   fine_chunks={len(fine_chunks)}")

        print(f"  [HIER-V16] fine indexing (retriever={self._fine.retriever_type})...")
        self._fine.index(fine_chunks, cache_context=fine_ctx)

        self._fine_chunks = fine_chunks
        self._fine_chunk_map = {c.chunk_id: c for c in fine_chunks}
        self._chunks_by_file = {}
        for c in fine_chunks:
            self._chunks_by_file.setdefault(c.file_path, []).append(c.chunk_id)

        self._indexed = True

    def index(self, chunks: List[Chunk]):
        raise NotImplementedError(
            "HierarchicalV16Retriever needs both coarse and fine chunks. "
            "Use index_repository(repo_path, python_files) instead of index(chunks)."
        )

    # ─── Retrieval ─────────────────────────────────────────────────

    def retrieve(self, query: str, k: int) -> List[Tuple[Chunk, float]]:
        if not self._indexed:
            raise RuntimeError("Call index_repository() first.")

        # ── Stage 1: Pre-computed LLM query → BM25 coarse ──
        if self.stage1_query_mode == "llm_expanded":
            expanded = self._lookup.lookup(query)
            if expanded:
                stage1_query = expanded
                self._expansion_hits += 1
            else:
                # Fallback: just use the title
                title = query.split("\n")[0].strip()
                stage1_query = title
                self._expansion_misses += 1
                print(f"    [V16] MISS: no expansion found, using title")
        elif self.stage1_query_mode == "title_only":
            stage1_query = query.split("\n")[0].strip()
        else:
            stage1_query = query

        self.last_stage1_query = stage1_query

        coarse_fetch = max(self.top_n_files * 3, 30)
        coarse_results = self._coarse.retrieve(stage1_query, coarse_fetch)

        # Aggregate to file-level scores
        file_scores: Dict[str, float] = {}
        for chunk, score in coarse_results:
            cur = file_scores.get(chunk.file_path)
            if self.coarse_score_aggregation == "sum":
                file_scores[chunk.file_path] = (cur or 0.0) + score
            else:  # "max"
                if cur is None or score > cur:
                    file_scores[chunk.file_path] = score

        candidate_files = sorted(file_scores.items(), key=lambda x: x[1], reverse=True)
        candidate_files = candidate_files[: self.top_n_files]
        candidate_set = {f for f, _ in candidate_files}
        self.last_coarse_files = [f for f, _ in candidate_files]

        if not candidate_set:
            return self._fine.retrieve(query, k)

        # ── Stage 2: Dense/Hybrid with Terms Filter ──
        if self.stage2_query_mode == "llm_expanded":
            expanded_s2 = self._lookup.lookup(query)
            stage2_query = expanded_s2 if expanded_s2 else query
        else:
            stage2_query = query  # full issue text

        results = self._retrieve_with_terms_filter(stage2_query, k, candidate_set)

        # Diagnostics
        from_candidates = [c for c, _ in results if c.file_path in candidate_set]
        from_fallback = [c for c, _ in results if c.file_path not in candidate_set]
        self.last_coarse_hit_count = len(from_candidates)
        self.last_stage2_from_candidate_files = len(from_candidates)
        self.last_stage2_from_fallback = len(from_fallback)
        return results

    def _retrieve_with_terms_filter(
        self,
        query: str,
        k: int,
        candidate_set: set,
    ) -> List[Tuple[Chunk, float]]:
        """Stage 2: Dense/Hybrid retrieval restricted to candidate files."""
        self._fine._init_es()
        if self._fine._embedding_model is None and self._fine.embedding_model_name:
            self._fine._init_embedding_model()

        file_list = list(candidate_set)

        if self._fine.retriever_type == "hybrid":
            results = self._hybrid_with_filter(query, k, file_list)
        elif self._fine.retriever_type == "dense":
            results = self._dense_with_filter(query, k, file_list)
        else:
            results = self._bm25_with_filter(query, k, file_list)

        # Map back to Chunk objects
        chunk_results: List[Tuple[Chunk, float]] = []
        for chunk_id, score in results:
            chunk = self._fine._chunk_map.get(chunk_id)
            if chunk:
                chunk_results.append((chunk, score))

        # Top up if needed
        if len(chunk_results) < k:
            unfiltered = self._fine.retrieve(query, k)
            seen = {c.chunk_id for c, _ in chunk_results}
            for chunk, score in unfiltered:
                if chunk.chunk_id not in seen:
                    chunk_results.append((chunk, score * 0.5))
                    if len(chunk_results) >= k:
                        break

        return chunk_results[:k]

    def _bm25_with_filter(self, query: str, k: int, file_list: List[str]) -> List[Tuple[str, float]]:
        body = {
            "query": {
                "bool": {
                    "must": {
                        "multi_match": {
                            "query": query,
                            "fields": ["title^3", "keywords^2", "content"],
                            "type": "best_fields",
                        }
                    },
                    "filter": {"terms": {"document_id": file_list}}
                }
            },
            "size": k,
        }
        res = self._fine._es_client.search(index=self._fine.index_name, body=body)
        return [
            (hit["_source"]["chunk_id"], float(hit["_score"]))
            for hit in res["hits"]["hits"]
        ]

    def _dense_with_filter(self, query: str, k: int, file_list: List[str]) -> List[Tuple[str, float]]:
        query_embedding = self._fine._encode_query(query).tolist()
        body = {
            "knn": {
                "field": "embedding",
                "query_vector": query_embedding,
                "k": k,
                "num_candidates": min(k * 10, len(self._fine_chunks)),
                "filter": {"terms": {"document_id": file_list}}
            },
            "_source": True,
        }
        res = self._fine._es_client.search(index=self._fine.index_name, body=body)
        return [
            (hit["_source"]["chunk_id"], float(hit["_score"]))
            for hit in res["hits"]["hits"]
        ]

    def _hybrid_with_filter(self, query: str, k: int, file_list: List[str]) -> List[Tuple[str, float]]:
        fetch_k = min(k * 3, len(self._fine_chunks))
        bm25_results = self._bm25_with_filter(query, fetch_k, file_list)
        dense_results = self._dense_with_filter(query, fetch_k, file_list)

        bm25_norm = self._normalize_scores_dict(bm25_results)
        dense_norm = self._normalize_scores_dict(dense_results)

        all_ids = set(bm25_norm.keys()) | set(dense_norm.keys())
        alpha = self._fine.hybrid_alpha
        fused = {}
        for cid in all_ids:
            bm25_s = bm25_norm.get(cid, 0.0)
            dense_s = dense_norm.get(cid, 0.0)
            fused[cid] = alpha * bm25_s + (1 - alpha) * dense_s

        ranked = sorted(fused.items(), key=lambda x: x[1], reverse=True)[:k]
        return ranked

    @staticmethod
    def _normalize_scores_dict(results: List[Tuple[str, float]]) -> Dict[str, float]:
        if not results:
            return {}
        scores = [s for _, s in results]
        min_s, max_s = min(scores), max(scores)
        spread = max_s - min_s
        if spread == 0:
            return {cid: 1.0 for cid, _ in results}
        return {cid: (s - min_s) / spread for cid, s in results}

    # ─── Lifecycle ─────────────────────────────────────────────────

    def cleanup(self):
        try:
            self._coarse.cleanup()
        finally:
            self._fine.cleanup()

    def close(self):
        try:
            self._coarse.close()
        finally:
            self._fine.close()
        self._fine_chunks = []
        self._fine_chunk_map = {}
        self._chunks_by_file = {}
        # Print expansion stats
        total = self._expansion_hits + self._expansion_misses
        if total > 0:
            print(f"  [V16] Expansion stats: {self._expansion_hits}/{total} hits "
                  f"({self._expansion_misses} misses)")

    def __del__(self):
        pass
